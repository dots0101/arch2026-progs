#!/usr/bin/env bash
set -euo pipefail
if [ "$#" -ne 1 ]; then
    echo "Usage: $0 OUTPUT_DIRECTORY" >&2
    exit 2
fi
task_out="$(python3 -c 'import os,sys;print(os.path.abspath(sys.argv[1]))' "$1")"
task_repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
mkdir -p "$task_out"
cd "$task_repo"
python3 - "$task_out/source_sha256.json" <<'PY'
import hashlib,json,sys
from pathlib import Path
paths=list(Path('src/rubik').glob('*'))+[Path('mytests/rubik_oracle.c')]
Path(sys.argv[1]).write_text(json.dumps({str(p):hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(paths) if p.is_file()},indent=2)+'\n')
PY
"${CC:-cc}" --version > "$task_out/compiler.txt"
"${CC:-cc}" -std=c11 -O3 -Wall -Wextra -Werror \
    mytests/rubik_oracle.c src/rubik/rubik.c src/rubik/n2_core_data.c \
    src/rubik/h48_b8_dist_table.c src/rubik/h48_exc_direct.c \
    src/rubik/h48_s3_base.c src/rubik/h48_t_simple_data.c \
    -o "$task_out/rubik_oracle"
"$task_out/rubik_oracle" "$task_out" | tee "$task_out/run.log"
python3 - "$task_out/rubik_d11.csv" "$task_out/rubik_d11_cases.inc" <<'PY'
import csv,sys
from pathlib import Path
rows=list(csv.DictReader(open(sys.argv[1])))
assert len(rows)==2644 and all(int(row['distance'])==11 for row in rows)
Path(sys.argv[2]).write_text('/* Generated by the independent host BFS, not used by the solver. */\n'+''.join('    "'+row['state']+'",\n' for row in rows))
PY
cmp mytests/rubik_d11_cases.inc "$task_out/rubik_d11_cases.inc"
